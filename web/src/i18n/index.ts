export type Dict = (typeof dict)['ru'];

export function getDict(lang: Lang): Dict {
  return dict[lang] as unknown as Dict;
}

export function formatDateTitle(iso: string, lang: Lang): { eyebrow: string; title: string } {
  const [y, m, d] = iso.split('-').map(Number);
  const t = getDict(lang);
  const wd = new Date(y, m - 1, d).getDay();
  if (lang === 'ru') return { eyebrow: t.weekdaysLong[wd], title: `${d} ${t.monthsGen[m - 1]}` };
  return { eyebrow: t.weekdaysLong[wd], title: `${t.months[m - 1]} ${d}` };
}

export function formatShortDate(iso: string, lang: Lang): string {
  const [, m, d] = iso.split('-').map(Number);
  const t = getDict(lang);
  return lang === 'ru' ? `${d} ${t.monthsGen[m - 1].slice(0, 3)}` : `${t.months[m - 1].slice(0, 3)} ${d}`;
}

/** "14 – 20 сен" when both dates share a month, otherwise "28 сен – 4 окт". */
export function formatRange(fromIso: string, toIso: string, lang: Lang): string {
  const [, m1, d1] = fromIso.split('-').map(Number);
  const [, m2, d2] = toIso.split('-').map(Number);
  const t = getDict(lang);
  if (m1 === m2) {
    return lang === 'ru' ? `${d1} – ${d2} ${t.monthsGen[m1 - 1].slice(0, 3)}` : `${t.months[m1 - 1].slice(0, 3)} ${d1} – ${d2}`;
  }
  return `${formatShortDate(fromIso, lang)} – ${formatShortDate(toIso, lang)}`;
}
